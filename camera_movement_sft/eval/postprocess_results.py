#!/usr/bin/env python3
"""
Post-process inference results: parse swift infer output into eval_pred.jsonl for evaluation.

swift infer output format (one entry per line):
    {"response": "<model output text>", "labels": "<ground_truth text>", ...}

This script produces:
    eval_pred.jsonl -- model predictions, ready for evaluate_camera_movement_fixed.py

The GT file does not need to be generated by this script; use the original annotation JSONL
(RAW_TEST_DATA) directly when running evaluation.

Usage:
    python camera_movement_sft/eval/postprocess_results.py \
        --infer_result path/to/infer_results.jsonl \
        --mapping path/to/video_id_mapping.jsonl \
        --output_dir path/to/checkpoint_dir

    # Also generate a debug file (contains raw_response, useful for troubleshooting)
    python camera_movement_sft/eval/postprocess_results.py \
        --infer_result path/to/infer_results.jsonl \
        --mapping path/to/video_id_mapping.jsonl \
        --output_dir path/to/checkpoint_dir \
        --debug
"""

import argparse
import json
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def parse_json_response(raw_text: str) -> dict:
    """Try to parse JSON from the model output."""
    if not raw_text:
        return {"raw": raw_text}

    # Direct parse.
    try:
        return json.loads(raw_text)
    except json.JSONDecodeError:
        pass

    # Try to extract a ```json ... ``` block.
    match = re.search(r"```(?:json)?\s*\n?(.*?)\n?```", raw_text, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(1))
        except json.JSONDecodeError:
            pass

    # Try to extract the first { ... } block.
    match = re.search(r"\{.*\}", raw_text, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(0))
        except json.JSONDecodeError:
            pass

    return {"raw": raw_text}


def load_jsonl(path: str) -> list:
    """Load a JSONL file."""
    items = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                items.append(json.loads(line))
    return items


def _vid_from_videos_field(videos_field):
    """Extract video_id from the 'videos' field in swift infer output (mp4 filename without extension).
    videos_field looks like ['/path/to/<video_id>.mp4'] or ['http://.../<video_id>.mp4?...'].
    Returns None if extraction fails."""
    if not videos_field:
        return None
    p = videos_field[0]
    if not isinstance(p, str):
        return None
    p = p.split("?")[0]
    fname = p.rsplit("/", 1)[-1]
    if "." in fname:
        fname = fname.rsplit(".", 1)[0]
    return fname or None


def _normalize_video_source(path_or_url):
    """Normalise a video path/URL for robust alignment between infer results and the mapping."""
    if not isinstance(path_or_url, str):
        return None
    p = path_or_url.strip()
    if not p:
        return None
    return p.split("?")[0]


def postprocess(infer_result_path, mapping_path, output_dir, debug=False):
    """Parse swift infer results and produce eval_pred.jsonl.

    video_id resolution priority:
      1. Align infer.videos[0] path with mapping.cos_url exactly.
         This avoids misalignment even when infer_results has fewer rows than the mapping.
      2. Fallback: use row index i to look up mappings[i].video_id (legacy logic,
         only when infer and mapping have the same length).
      3. Extract from the infer.videos filename.
      4. Use "unknown_<i>".
    """
    mappings = load_jsonl(mapping_path)
    results = load_jsonl(infer_result_path)

    print(f"[INFO] Mapping entries: {len(mappings)}")
    print(f"[INFO] Inference results: {len(results)}")
    if len(mappings) != len(results):
        print(f"[WARN] Row count mismatch (map={len(mappings)} vs infer={len(results)}); "
              f"will prefer infer.videos field for video_id extraction to avoid misalignment")

    # Build a "video source path -> GT video_id" index from the mapping to handle clip scenarios
    # (GT video_id like "xxx__seg0" while the actual filename may be "xxx_0.mp4").
    mapping_by_source = {}
    for m in mappings:
        vid = m.get("video_id")
        src = _normalize_video_source(m.get("cos_url"))
        if isinstance(vid, str) and vid and src:
            mapping_by_source[src] = vid

    os.makedirs(output_dir, exist_ok=True)
    pred_path = os.path.join(output_dir, "eval_pred.jsonl")

    stats = {"success": 0, "parse_error": 0,
             "vid_from_mapping_src": 0,
             "vid_from_mapping_idx": 0,
             "vid_from_videos": 0,
             "vid_unknown": 0}
    debug_items = [] if debug else None

    with open(pred_path, "w", encoding="utf-8") as f_pred:
        for i, result in enumerate(results):
            raw_response = result.get("response", "")

            # Resolve video_id (priority order):
            # 1) Exact match of infer.videos[0] path with mapping.cos_url.
            # 2) Row-index alignment (only when infer and mapping have the same length).
            # 3) Extract from infer.videos filename.
            # 4) unknown.
            video_id = None
            videos_field = result.get("videos")
            src = _normalize_video_source(videos_field[0]) if isinstance(videos_field, list) and videos_field else None
            if src and src in mapping_by_source:
                video_id = mapping_by_source[src]
                stats["vid_from_mapping_src"] += 1
            elif len(results) == len(mappings) and i < len(mappings):
                video_id = mappings[i].get("video_id")
                if video_id:
                    stats["vid_from_mapping_idx"] += 1

            if not video_id:
                video_id = _vid_from_videos_field(videos_field)
                if video_id:
                    stats["vid_from_videos"] += 1
                else:
                    video_id = f"unknown_{i}"
                    stats["vid_unknown"] += 1

            # Parse the model output.
            prediction = parse_json_response(raw_response)

            if "segments" in prediction:
                stats["success"] += 1
                pred_segs = prediction["segments"]
            elif "raw" in prediction:
                stats["parse_error"] += 1
                pred_segs = []
            else:
                stats["success"] += 1
                pred_segs = prediction.get("segments", [])

            # Write eval_pred entry.
            f_pred.write(json.dumps(
                {"video_id": video_id, "segments": pred_segs},
                ensure_ascii=False
            ) + "\n")

            # Debug mode: record full info.
            if debug:
                debug_items.append({
                    "video_id": video_id,
                    "raw_response": raw_response,
                    "parsed_segments": pred_segs,
                    "status": "success" if "raw" not in prediction else "parse_error",
                })

    print(f"\n[INFO] Post-processing done!")
    print(f"  Parsed successfully: {stats['success']}")
    print(f"  Parse errors:        {stats['parse_error']}")
    print(
        "  video_id source: "
        f"mapping[cos_url]={stats['vid_from_mapping_src']}  "
        f"mapping[idx]={stats['vid_from_mapping_idx']}  "
        f"videos_field={stats['vid_from_videos']}  "
        f"unknown={stats['vid_unknown']}"
    )
    print(f"  eval_pred: {pred_path}")

    # Debug mode: write the full debug file.
    if debug and debug_items:
        debug_path = os.path.join(output_dir, "debug_full_results.jsonl")
        with open(debug_path, "w", encoding="utf-8") as f:
            for item in debug_items:
                f.write(json.dumps(item, ensure_ascii=False) + "\n")
        print(f"  debug file: {debug_path}")


def main():
    parser = argparse.ArgumentParser(description="Post-process swift infer results")
    parser.add_argument(
        "--infer_result", type=str, required=True,
        help="JSONL file output by swift infer"
    )
    parser.add_argument(
        "--mapping", type=str, required=True,
        help="video_id mapping file"
    )
    parser.add_argument(
        "--output_dir", type=str, required=True,
        help="output directory (eval_pred.jsonl is written here)"
    )
    parser.add_argument(
        "--debug", action="store_true",
        help="also generate debug_full_results.jsonl (contains raw_response, useful for troubleshooting)"
    )
    # Backwards compatibility: --output is accepted but ignored.
    parser.add_argument("--output", type=str, default=None, help=argparse.SUPPRESS)
    parser.add_argument("--no_eval_files", action="store_true", help=argparse.SUPPRESS)

    args = parser.parse_args()

    # Legacy call style: if --output was used without --output_dir, derive output_dir from --output.
    if args.output and not args.output_dir:
        args.output_dir = os.path.dirname(args.output) or "."

    postprocess(args.infer_result, args.mapping, args.output_dir, args.debug)


if __name__ == "__main__":
    main()
